import type {WeaponId} from '../src/config';
import Phaser from 'phaser';
import {ArenaScene} from '../src/combat';
import {freshSave} from '../src/save';
import {AudioManager} from '../src/audio';
import {WEAPON_EFFECTS} from '../src/weapon-effects';
const scene=new ArenaScene(freshSave(),new AudioManager(),()=>{},()=>{},()=>{});
new Phaser.Game({type:Phaser.CANVAS,parent:'game',width:innerWidth,height:innerHeight,scene:[scene],scale:{mode:Phaser.Scale.RESIZE},audio:{noAudio:true}});
let weapon:WeaponId='katana',sequence=0;
document.querySelector<HTMLSelectElement>('#weapon')!.onchange=(e)=>{weapon=(e.target as HTMLSelectElement).value as WeaponId;attack=0;scrub=undefined;};
let attack=0,scrub:number|undefined;
for(const button of Array.from(document.querySelectorAll<HTMLButtonElement>('[data-pose]')))button.onclick=()=>{scrub=Number(button.dataset.pose);};
document.querySelector('#zoom')!.addEventListener('click',()=>scene.cameras.main.setZoom(scene.cameras.main.zoom>1.1?1:Math.min(2,innerWidth/500)));
document.querySelector('#attack')!.addEventListener('click',()=>{scrub=undefined;sequence++;attack=WEAPON_EFFECTS[weapon].duration;});
const ready=setInterval(()=>{if(!scene.visuals)return;clearInterval(ready);scene.paused=true;scene.stats.wave=1;scene.x=600;scene.y=400;
 for(const e of scene.enemies)e.active=false;
 const zombie=scene.spawn('basic',0,.5,'zombie')!,robot=scene.spawn('spitter',1,.5,'robot')!;
 zombie.x=600;zombie.y=400;robot.x=780;robot.y=400;
 for(const [x,name] of [[420,'NINJA'],[600,'WANDERER'],[780,'PULSE ROBOT']] as const)scene.add.text(x,470,name,{fontSize:'15px',color:'#f2ebd6',stroke:'#18232e',strokeThickness:4}).setOrigin(.5).setDepth(9);
 scene.cameras.main.centerOn(600,400);let last=performance.now(),travel=0;
 const tick=(now:number)=>{const dt=Math.min(.04,(now-last)/1000);last=now;scene.elapsed+=dt;travel+=dt*30;attack=Math.max(0,attack-dt);
 const offset=20*Math.sin(travel/20);zombie.x=600+offset;robot.x=780+offset;scene.x=420+offset;
 scene.cameras.main.centerOn(600,400);scene.gfx.clear();scene.warningGfx.clear();scene.drawWorld();scene.visuals.render([zombie,robot], 'ninja',weapon,scene.x,400,0,scene.elapsed,scrub===undefined?attack:WEAPON_EFFECTS[weapon].duration*(1-scrub),0,0,false,0,scene.ammo,sequence);
 requestAnimationFrame(tick);};requestAnimationFrame(tick);
},50);
